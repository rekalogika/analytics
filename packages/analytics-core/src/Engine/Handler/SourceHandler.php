namespace Rekalogika\Analytics\Engine\Handler;

use Rekalogika\Analytics\Engine\Entity\DirtyFlag;
use Rekalogika\Analytics\Metadata\Source\SourceMetadata;

final readonly class SourceHandler
{
    public function __construct(
        private SourceMetadata $sourceMetadata,
        private HandlerFactory $handlerFactory,
    ) {}

    /**
     * @return class-string
     */
    public function getSourceClass(): string
    {
        return $this->sourceMetadata->getClass();
    }

    /**
     * @return iterable<DirtyFlag>
     */
    public function generateDirtyFlagsForEntityCreation(object $entity): iterable
    {
        $summaryClasses = $this->sourceMetadata->getAllInvolvedSummaryClasses();

        foreach ($summaryClasses as $summaryClass) {
            yield new DirtyFlag(
                class: $summaryClass,
                level: null,
                key: null,
            );
        }
    }

    /**
     * Generates the dirty flags of the lowest partitions containing a new
     * entity. Unlike the new entity flags above, these do not depend on the
     * latest summarized key, so they cover entities committed after a refresh
     * has already moved the latest key past their keys. Must be called after
     * the insert, so that a key generated by the database is already known.
     *
     * @return iterable<DirtyFlag>
     */
    public function generatePartitionDirtyFlagsForEntityCreation(object $entity): iterable
    {
        $summaryClasses = $this->sourceMetadata->getAllInvolvedSummaryClasses();

        foreach ($summaryClasses as $summaryClass) {
            $summaryHandler = $this->handlerFactory->getSummary($summaryClass);

            $partition = $summaryHandler
                ->getPartition()
                ->tryGetLowestPartitionFromEntity($entity);

            // entities without a partitioning key are never summarized

            if ($partition === null) {
                continue;
            }

            yield $summaryHandler
                ->getDirtyFlags()
                ->createDirtyFlagForPartition($partition);
        }
    }

    /**
     * @return iterable<DirtyFlag>
     */
    public function generateDirtyFlagsForEntityDeletion(object $entity): iterable
    {
        $summaryClasses = $this->sourceMetadata->getAllInvolvedSummaryClasses();

        foreach ($summaryClasses as $summaryClass) {
            $dirtyFlagHandler = $this->handlerFactory
                ->getSummary($summaryClass)
                ->getDirtyFlags();

            yield $dirtyFlagHandler->createDirtyFlagForSourceEntity($entity);
        }
    }

    /**
     * Generates the dirty flags of the partitions affected by a modification
     * of an entity. If the partitioning key is modified, the entity moves to
     * another partition, and the partition it was in before the modification
     * is also flagged.
     *
     * @param list<string> $modifiedProperties
     * @param array<string,mixed> $originalValues The values of the modified
     * properties before the modification, keyed by the property name. A
     * modified property without an original value is assumed not to change
     * the partition of the entity.
     * @return iterable<DirtyFlag>
     */
    public function generateDirtyFlagsForEntityModification(
        object $entity,
        array $modifiedProperties,
        array $originalValues = [],
    ): iterable {
        $summaryClasses = $this->sourceMetadata
            ->getInvolvedSummaryClassesByChangedProperties($modifiedProperties);

        foreach ($summaryClasses as $summaryClass) {
            $summaryHandler = $this->handlerFactory->getSummary($summaryClass);
            $dirtyFlagHandler = $summaryHandler->getDirtyFlags();

            yield $dirtyFlagHandler->createDirtyFlagForSourceEntity($entity);

            $originalPartition = $summaryHandler
                ->getPartition()
                ->tryGetOriginalLowestPartition($originalValues);

            if ($originalPartition !== null) {
                yield $dirtyFlagHandler->createDirtyFlagForPartition($originalPartition);
            }
        }
    }
}
